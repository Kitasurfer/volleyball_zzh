export function useMatchText() {
  const { language } = useLanguage();
  const index = { de: 0, en: 1, ru: 2, it: 3 }[language];
  const t = (key: keyof typeof labels) => labels[key][index];
  return { t, language };
}

export type MatchText = ReturnType<typeof useMatchText>['t'];
export function matchError(error: unknown, t: MatchText) {
  switch (error instanceof Error ? error.message : '') {
    case 'access_denied': return t('denied');
    case 'lease_taken': case 'lease_lost': return t('leaseTaken');
    case 'schedule_overlap': return t('overlap');
    case 'invalid_time': return t('invalidTime');
    case 'invalid_set_history': return t('invalidSetHistory');
    case 'account_not_found': return t('accountMissing');
    case 'rules_locked': return t('rulesLocked');
    case 'schedule_exists': return t('scheduleExists');
    case 'queue_full': return t('queueFull');
    case 'version_conflict': case 'device_conflict': return t('conflict');
    default: return t('error');
  }
}
